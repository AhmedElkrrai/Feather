"""
Turns the chosen owl feathers (art/feathers/chosen/days-N.svg, made by Recraft) into Android vector drawables
(app/src/main/res/drawable/feather_days_N.xml). N is the number of days of last week with a finished task, 0 to 7.

The feather SVGs are plain: absolute M, L, C and Z paths, filled with a solid color (maybe with an opacity) or a linear gradient in
user space. Android's vector format has all of that. Run it from anywhere: python art/feathers/make_vectors.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'app', 'src', 'main', 'res', 'drawable')


def argb(color, opacity=1.0):
    c = color.lstrip('#')
    if len(c) == 3:
        c = ''.join(ch * 2 for ch in c)
    alpha = round(max(0.0, min(1.0, opacity)) * 255)
    return f'#{alpha:02X}{c.upper()}'


def convert(svg):
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]
    grads = {}
    for m in re.finditer(r'<linearGradient\b([^>]*)>(.*?)</linearGradient>', svg, re.S):
        attrs = dict(re.findall(r'([\w:-]+)="([^"]*)"', m.group(1)))
        stops = [dict(re.findall(r'([\w:-]+)="([^"]*)"', s)) for s in re.findall(r'<stop\b([^>]*)/?>', m.group(2))]
        grads[attrs['id']] = (attrs, stops)
    lines = []
    for m in re.finditer(r'<path\b([^>]*?)/?>', svg):
        attrs = dict(re.findall(r'([\w:-]+)="([^"]*)"', m.group(1)))
        d = attrs.get('d')
        if not d:
            continue
        fill = attrs.get('fill', '#000000')
        opacity = float(attrs.get('fill-opacity', '1'))
        url = re.match(r'url\(#([^)]+)\)', fill)
        if url and url.group(1) in grads:
            g, stops = grads[url.group(1)]
            items = ''.join(
                f'\n                    <item android:offset="{float(s.get("offset", "0")):g}" android:color="{argb(s.get("stop-color", "#000000"))}" />'
                for s in stops
            )
            alpha = f'\n            android:fillAlpha="{opacity:g}"' if opacity < 1 else ''
            lines.append(
                f'        <path\n            android:pathData="{d}"{alpha}>\n'
                f'            <aapt:attr name="android:fillColor">\n'
                f'                <gradient\n'
                f'                    android:type="linear"\n'
                f'                    android:startX="{g["x1"]}"\n                    android:startY="{g["y1"]}"\n'
                f'                    android:endX="{g["x2"]}"\n                    android:endY="{g["y2"]}">{items}\n'
                f'                </gradient>\n'
                f'            </aapt:attr>\n'
                f'        </path>'
            )
        else:
            lines.append(f'        <path\n            android:fillColor="{argb(fill, opacity)}"\n            android:pathData="{d}" />')
    width, height = vb[2], vb[3]
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- A feather of the owl: generated by art/feathers/make_vectors.py from art/feathers/chosen. Do not edit by hand. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        f'    android:width="{width / 2.5:.0f}dp"\n    android:height="{height / 2.5:.0f}dp"\n'
        f'    android:viewportWidth="{width:g}"\n    android:viewportHeight="{height:g}">\n'
        f'    <group android:translateX="{-vb[0]:g}" android:translateY="{-vb[1]:g}">\n'
        + '\n'.join(lines) + '\n    </group>\n</vector>\n'
    )


if __name__ == '__main__':
    for n in range(8):
        src = open(os.path.join(HERE, 'chosen', f'days-{n}.svg'), encoding='utf-8').read()
        xml = convert(src)
        path = os.path.join(OUT, f'feather_days_{n}.xml')
        open(path, 'w', encoding='utf-8', newline='\n').write(xml)
        print(f'feather_days_{n}.xml', len(xml) // 1024, 'KB', xml.count('<path'), 'paths')
